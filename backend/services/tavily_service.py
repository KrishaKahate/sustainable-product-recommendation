"""
Tavily search service — performs web research using queries generated by Grok
and returns normalised search results with source URLs.
"""

import logging
import requests
from backend.config import TAVILY_API_KEY, TAVILY_API_URL, TAVILY_TIMEOUT, TAVILY_MAX_RESULTS_PER_QUERY

logger = logging.getLogger(__name__)


def _search_single(query: str) -> list[dict]:
    """Execute one Tavily search and return its results list."""
    if not TAVILY_API_KEY:
        raise ValueError("TAVILY_API_KEY is not configured.")

    payload = {
        "api_key": TAVILY_API_KEY,
        "query": query,
        "max_results": TAVILY_MAX_RESULTS_PER_QUERY,
        "search_depth": "basic",
        "include_answer": False,
        "include_raw_content": False,
    }

    try:
        response = requests.post(
            TAVILY_API_URL,
            json=payload,
            timeout=TAVILY_TIMEOUT,
        )
        response.raise_for_status()
        data = response.json()
        return data.get("results", [])

    except requests.exceptions.Timeout:
        logger.warning("Tavily search timed out for query: %s", query)
        return []

    except requests.exceptions.RequestException as exc:
        logger.warning("Tavily search failed for query '%s': %s", query, exc)
        return []


def search(queries: list[str]) -> list[dict]:
    """
    Run multiple Tavily searches, aggregate results, and deduplicate by URL.

    Each result dict contains at minimum:
      - url       (str)
      - title     (str)
      - content   (str)  — snippet/description
      - score     (float, optional) — Tavily relevance score
    """
    seen_urls: set[str] = set()
    aggregated: list[dict] = []

    for query in queries:
        logger.info("Tavily search: %s", query)
        results = _search_single(query)

        for result in results:
            url = result.get("url", "")
            if not url or url in seen_urls:
                continue
            seen_urls.add(url)

            aggregated.append({
                "url": url,
                "title": result.get("title", ""),
                "content": result.get("content", ""),
                "score": result.get("score"),
            })

    logger.info(
        "Tavily returned %d unique results from %d queries",
        len(aggregated),
        len(queries),
    )
    return aggregated
